//! SDK documentation output policy: the `README.md` and `reference.md` an SDK target writes.
//!
//! Both are rendered from the docs model (`crate::docs`), built for this one SDK — the same builder
//! and the same renderer `StaticDocs` uses, viewed as a single file. The README's package lines name
//! the one consumer identity, and its quick start is the first sampled operation's call, byte for
//! byte as `reference.md` (and a `StaticDocs` page) prints it.

use std::fmt::Write as _;

use crate::docs::build::language_name;
use crate::docs::identity::{error_type, NO_IDENTITY_NOTE};
use crate::docs::markdown::escape::code_span;
use crate::docs::markdown::render;
use crate::docs::model::{DocsModel, ExampleDoc, SdkSamples, View};
use crate::graph::ApiGraph;
use crate::sdk::builtins::SiblingSdk;
use crate::sdk::Artifacts;
use crate::verify::ContractTestLanguage;
use crate::CoreError;

pub use gnr8::sdk::docs::SdkDocs;

/// Write the SDK's `README.md` and `reference.md` under its directory, from `ir` — the projected
/// graph the SDK itself is emitted from.
///
/// # Errors
///
/// Returns what the docs model's builder or renderer returns: an invalid declared example, prose
/// that breaks `reference.md`'s structure, or a sample that cannot be printed.
pub(crate) fn write_sdk_docs(
    out: &mut Artifacts,
    sdk: SiblingSdk<'_>,
    ir: &ApiGraph,
    docs: &SdkDocs,
) -> Result<(), CoreError> {
    if docs.is_none() {
        return Ok(());
    }
    let dir = sdk.dir().trim_end_matches('/');
    let model = DocsModel::build(ir, &[sdk], View::Sdk)?;
    out.create(format!("{dir}/README.md"), sdk_readme(&model, sdk))?;
    out.create(
        format!("{dir}/reference.md"),
        render::sdk_reference(&model, &format!("{dir}/reference.md"))?,
    )?;
    Ok(())
}

/// The first sampled operation's call for the model's one SDK: its id, request line and sample
/// block — the quick start, which `reference.md` prints byte for byte under that operation.
pub(crate) fn quick_start(model: &DocsModel) -> Option<(&str, &str, String)> {
    model.operations.iter().find_map(|op| match &op.example {
        ExampleDoc::Sampled { per_sdk, .. } => match per_sdk.first() {
            Some(SdkSamples::Code(samples)) => Some((
                op.id.as_str(),
                op.request_line.as_str(),
                render::sample_block(&samples.call),
            )),
            _ => None,
        },
        ExampleDoc::Refused(_) => None,
    })
}

fn sdk_readme(model: &DocsModel, sdk: SiblingSdk<'_>) -> String {
    let language = sdk.language();
    let name = language_name(language);
    let identity = model.sdks.first().and_then(|doc| doc.identity.as_ref());
    let mut text = format!(
        "# {title} {name} SDK\n\n\
         This directory is generated by `gnr8`. Do not edit generated files directly; edit \
         `.gnr8/src/main.rs` or the source service, then run `gnr8 generate`.\n\n\
         ## Package\n\n\
         - Language: {name}\n",
        title = model.api.title.trim(),
    );
    if let Some(identity) = identity {
        let _ = writeln!(text, "- Import: {}", code_span(identity.import()));
        let _ = writeln!(
            text,
            "- Install: {}",
            code_span(&identity.install_command())
        );
    }
    let _ = write!(
        text,
        "- Base path: `{base_path}`\n- Operations: {operations}\n- Schemas: {schemas}\n\n",
        base_path = model.api.base_path.as_deref().unwrap_or("/"),
        operations = model.operations.len(),
        schemas = model.schemas.len(),
    );
    if identity.is_none() {
        let _ = writeln!(text, "{NO_IDENTITY_NOTE}\n");
    }
    text.push_str("## Agent workflow\n\n");
    text.push_str(
        "1. Read `reference.md` in this directory for every operation, schema, error and \
         credential, each operation with its sample.\n",
    );
    let construct = match language {
        ContractTestLanguage::TypeScript => {
            "2. Construct the generated `Client` with `{ baseUrl }`.\n"
        }
        ContractTestLanguage::Go | ContractTestLanguage::Python => {
            "2. Construct the generated `Client` with the service base URL.\n"
        }
    };
    text.push_str(construct);
    text.push_str(
        "3. Pass typed request models and path/query parameters according to the generated method signatures.\n",
    );
    // The error type is named as this language's emitter spells it.
    let _ = writeln!(
        text,
        "4. Handle generated {} values for rejected HTTP responses.\n",
        code_span(&error_type(language))
    );
    // The timeout knob does not bound the same span in every language, and a caller who assumes
    // it does will size it wrong. Say so where they will read it.
    text.push_str(match language {
        ContractTestLanguage::Go => concat!(
            "## Retries and timeouts\n\n",
            "`WithTimeout` bounds the whole call, including retries and the waits between them. ",
            "Total time spent waiting between retries is capped at 60s, so a longer `Retry-After` ",
            "is honoured only up to that cap. Cancelling the context interrupts a retry wait.\n\n"
        ),
        ContractTestLanguage::Python => concat!(
            "## Retries and timeouts\n\n",
            "`timeout` bounds each individual attempt, not the whole call: with retries, total ",
            "wall time can reach `timeout x (max_retries + 1)` plus the waits between them. ",
            "Total time spent waiting between retries is capped at 60s, so a longer `Retry-After` ",
            "is honoured only up to that cap. Retry waits are not interruptible.\n\n"
        ),
        ContractTestLanguage::TypeScript => concat!(
            "## Retries and timeouts\n\n",
            "`timeoutMs` bounds each individual attempt, not the whole call: with retries, total ",
            "wall time can reach `timeoutMs x (maxRetries + 1)` plus the waits between them. ",
            "Total time spent waiting between retries is capped at 60s, so a longer `Retry-After` ",
            "is honoured only up to that cap. Pass `signal` to interrupt a retry wait.\n\n"
        ),
    });
    text.push_str("## Quick start\n\n");
    match (identity, quick_start(model)) {
        (None, _) => {
            let _ = writeln!(text, "{NO_IDENTITY_NOTE}");
        }
        (Some(_), None) => text.push_str(
            "No operation has a sample call; `reference.md` says why under each operation.\n",
        ),
        (Some(_), Some((operation, request_line, block))) => {
            let _ = write!(
                text,
                "Calling {} ({}), as `reference.md` prints it:\n\n{block}",
                code_span(operation),
                code_span(request_line)
            );
        }
    }
    text
}

/// The stable code for "a package loader stage failed", which the reference never publishes.
///
/// Matching the CODE is what this identity is for — it is the same key `DiagnosticPolicy` matches
/// on — so this is a policy decision about a class of diagnostic, not a reading of its text.
const SOURCE_LOAD_FAILED: &str = "source.load.failed";

/// Whether a diagnostic belongs in a published SDK reference.
///
/// Two clauses, for two different reasons. Both exist because a generated document is COMMITTED:
/// it is read by people who did not run the pipeline, and it is compared byte-for-byte by
/// `gnr8 check`.
///
/// 1. **The location must name a file inside the analyzed module.** A location outside it — a
///    dependency, the standard library, a downloaded toolchain under the module cache — is not a
///    fact about the API this document describes, and it is machine-dependent: it holds the
///    reader's home directory and module-cache layout. Publishing one makes two developers with
///    byte-identical source commit different bytes, which surfaces as `gnr8 check` drift that no
///    source change explains (issue #67).
///
/// 2. **It must describe the API, not whether the source could be read at all.** A load failure
///    means there was no surface to describe, so it is not a gap in the published contract — and
///    its message is the package loader's own text, which can quote a filesystem path wherever the
///    loader chose to. Excluding the class removes that whole exposure without gnr8 ever reading a
///    diagnostic's message to decide.
///
/// Nothing is lost. Every diagnostic still travels with the graph and still reaches
/// `gnr8 inspect graph`, `gnr8 doctor` (which exits non-zero on error severity), and `-v` output —
/// reports, rather than committed artifacts.
pub(crate) fn is_publishable(diagnostic: &crate::graph::Diagnostic) -> bool {
    crate::graph::is_module_relative(&diagnostic.file) && diagnostic.code != SOURCE_LOAD_FAILED
}

