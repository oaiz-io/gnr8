    /// Every file an SDK's docs write, by path.
    fn sdk_docs(
        sdk: SiblingSdk<'_>,
        graph: &ApiGraph,
    ) -> std::collections::BTreeMap<String, String> {
        let mut out = Artifacts::new();
        let docs = SdkDocs::from(true);
        write_sdk_docs(&mut out, sdk, graph, &docs).unwrap();
        out.into_files()
            .into_iter()
            .map(|artifact| (artifact.path, artifact.text))
            .collect()
    }

    /// The README names the one consumer identity — what to import and the language's own install
    /// command — and its quick start is the first sampled call, byte for byte as `reference.md`
    /// prints it under that operation.
    #[test]
    fn readme_names_the_identity_and_quotes_the_reference_call() {
        let py = PySdk::new()
            .module("example.com/shop/shop")
            .package(SdkPackageMetadata::new().registry_name("shop-sdk"))
            .to("py");
        let files = sdk_docs(SiblingSdk::Python(&py), &shop());
        let readme = &files["py/README.md"];
        assert!(
            readme.contains("- Import: `shop`\n- Install: `pip install shop-sdk`\n"),
            "{readme}"
        );
        assert!(
            readme.contains("4. Handle generated `ApiError` values"),
            "{readme}"
        );
        let block = readme
            .split("## Quick start\n\n")
            .nth(1)
            .and_then(|rest| rest.split_once("\n\n"))
            .map(|(intro, block)| {
                assert_eq!(
                    intro,
                    "Calling `getItem` (`GET /items/{id}`), as `reference.md` prints it:"
                );
                block
            })
            .unwrap();
        assert!(
            block.starts_with("```python\nfrom shop import Client\n"),
            "{block}"
        );
        assert!(files["py/reference.md"].contains(block), "{block}");
    }

    /// An SDK with no package metadata has no import to name, so its README says so in place of
    /// the import, the install line and the quick start.
    #[test]
    fn readme_without_an_identity_says_why_it_has_no_quick_start() {
        let ts = TsSdk::new().module("shop").to("ts");
        let files = sdk_docs(SiblingSdk::TypeScript(&ts), &shop());
        let readme = &files["ts/README.md"];
        assert!(!readme.contains("- Import:"), "{readme}");
        assert!(!readme.contains("- Install:"), "{readme}");
        assert!(
            readme.ends_with(&format!("## Quick start\n\n{}\n", super::NO_IDENTITY_NOTE)),
            "{readme}"
        );
    }

    /// `reference.md` is one file: the docs pages as sections one heading level down under its own
    /// title, its one link `README.md`, every other reference a code span, and errors, credentials
    /// and samples scoped to this SDK alone. A diagnostic naming no operation is printed once, its
    /// path with `/`.
    #[test]
    fn reference_is_one_file_scoped_to_its_sdk() {
        let go = GoSdk::new().module("example.com/shop/sdk").to("go");
        let files = sdk_docs(SiblingSdk::Go(&go), &shop());
        let reference = &files["go/reference.md"];
        assert!(
            reference.starts_with(
                "# Shop API Go SDK reference\n\nGenerated by `gnr8` for `example.com/shop/sdk`. \
                 [README.md](README.md) shows how to install it and construct the client.\n\n## Shop API\n"
            ),
            "{reference}"
        );
        assert_eq!(reference.matches("\n# ").count(), 0, "{reference}");
        assert_eq!(reference.matches("](").count(), 1, "{reference}");
        for section in [
            "\n## `getItem`\n",
            "\n### Example\n",
            "\n#### Go — `example.com/shop/sdk`\n",
            "\n## `Problem`\n",
            "\n## Errors\n",
            "\n## Authentication\n",
            "\n### `ApiKeyAuth`\n",
        ] {
            assert!(reference.contains(section), "{section} in:\n{reference}");
        }
        assert!(
            reference.contains("including a status the API does not declare: Go `*APIError`.\n"),
            "{reference}"
        );
        assert!(!reference.contains("Python"), "{reference}");
        assert!(!reference.contains("TypeScript"), "{reference}");
        assert!(
            reference.contains("Handling the `404` reply:"),
            "{reference}"
        );
        assert_eq!(
            reference
                .matches("- WARN: server path dropped (api/spec.yaml:3)\n")
                .count(),
            1,
            "{reference}"
        );
    }
