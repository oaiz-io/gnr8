//! Generation of Rust SDK source trees.

use std::collections::BTreeSet;

use crate::graph::ApiGraph;
use crate::sdk::bundle::SdkFile;
use crate::sdk::layout::SdkFileLayout;
use crate::CoreError;

pub(crate) fn generate_files(
    graph: &ApiGraph,
    selected: &BTreeSet<&str>,
    layout: &SdkFileLayout,
    package_metadata: bool,
) -> Result<Vec<SdkFile>, CoreError> {
    let prefix = if package_metadata { "src/" } else { "" };
    let model_layout = if layout.is_split() && layout.model_dir_ref() == Some("models") {
        layout.clone().root_models()
    } else {
        layout.clone()
    };
    let mut files = crate::rustmodels::generate_files(graph, selected, &model_layout)?;
    for file in &mut files {
        file.name = if !layout.is_split() && file.name == "mod.rs" {
            format!("{prefix}models.rs")
        } else {
            format!("{prefix}models/{}", file.name)
        };
    }
    files.push(SdkFile {
        name: format!(
            "{prefix}{}",
            if package_metadata { "lib.rs" } else { "mod.rs" }
        ),
        contents: "//! Rust SDK generated by gnr8.\n\npub mod models;\n".to_string(),
    });
    files.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(files)
}
